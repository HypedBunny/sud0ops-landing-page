// Bundles the markdown posts in src/content/blog into a TypeScript module, so the site
// never reads files at runtime (it runs on Cloudflare Workers). Runs before dev and build.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../src/content/blog/", import.meta.url);
const sources = {};
for (const file of readdirSync(dir).filter((name) => name.endsWith(".md")).sort()) {
    const slug = file.slice(0, -3);
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug)) {
        throw new Error(`Blog post file "${file}" must be named like my-post-title.md (lowercase, hyphens).`);
    }
    sources[slug] = readFileSync(new URL(file, dir), "utf8");
}

writeFileSync(
    new URL("posts.generated.ts", dir),
    `// Generated by scripts/generate-blog.mjs from the .md files in this folder. Do not edit.\n` +
        `export const sources: Record<string, string> = ${JSON.stringify(sources, null, 4)};\n`,
);
console.log(`Blog: bundled ${Object.keys(sources).length} post(s).`);
